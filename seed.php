try {
    $pdo = db();
    $adminId = $pdo->query('SELECT id FROM admins ORDER BY id LIMIT 1')->fetchColumn();
    if (!$adminId) {
        throw new RuntimeException('Create an admin first by running create-admin.php.');
    }

    $pdo->beginTransaction();
    $findCategory = $pdo->prepare('SELECT id FROM categories WHERE slug = :slug LIMIT 1');
    $createCategory = $pdo->prepare('INSERT INTO categories (name, slug) VALUES (:name, :slug)');
    $categoryIds = [];
    foreach (['Tutorials', 'Engineering', 'Design', 'Community'] as $name) {
        $slug = strtolower($name);
        $findCategory->execute(['slug' => $slug]);
        $categoryId = $findCategory->fetchColumn();
        if (!$categoryId) {
            $createCategory->execute(['name' => $name, 'slug' => $slug]);
            $categoryId = $pdo->lastInsertId();
        }
        $categoryIds[$name] = (int) $categoryId;
    }

    $findPost = $pdo->prepare('SELECT id FROM posts WHERE slug = :slug LIMIT 1');
    $createPost = $pdo->prepare(
        "INSERT INTO posts
         (category_id, author_id, title, slug, excerpt, body, status, published_at)
         VALUES (:category_id, :author_id, :title, :slug, :excerpt, :body, 'published', CURRENT_TIMESTAMP)"
    );
    $created = 0;
    $skipped = 0;
    foreach ($seedPosts as $post) {
        $slug = strtolower(trim((string) preg_replace('/[^a-z0-9]+/i', '-', $post['title']), '-'));
        $findPost->execute(['slug' => $slug]);
        if ($findPost->fetchColumn()) {
            $skipped++;
            continue;
        }

        $createPost->execute([
            'category_id' => $categoryIds[$post['category']],
            'author_id' => (int) $adminId,
            'title' => $post['title'],
            'slug' => $slug,
            'excerpt' => $post['excerpt'],
            'body' => $post['body'],
        ]);
        $created++;
    }
    $pdo->commit();
    fwrite(STDOUT, "Seed complete: {$created} posts created, {$skipped} existing posts skipped.\n");
} catch (Throwable $exception) {
    if (isset($pdo) && $pdo instanceof PDO && $pdo->inTransaction()) {
        $pdo->rollBack();
    }
    fwrite(STDERR, 'Seed failed: ' . $exception->getMessage() . PHP_EOL);
    exit(1);
}
